import React, { useEffect, useState, useCallback, useRef } from 'react';
import { fetchJSON } from '../api';
import { useAuth } from '../AuthContext';
import { FlowBadge } from './Scenarios';
import { NetworkBadge } from '../components/NetworkBadge';
import { SearchInput } from '../components/SearchInput';
import { Pagination } from './Transactions';

const PER_PAGE = 20;

export default function ScenarioRunner() {
  const { canDo } = useAuth();
  const [scenarios, setScenarios] = useState([]);
  const [runs, setRuns] = useState([]);
  const [total, setTotal] = useState(0);
  const [page, setPage] = useState(1);
  const [loading, setLoading] = useState(true);
  const [running, setRunning] = useState(null);

  // Active run state
  const [activeRun, setActiveRun] = useState(null);
  const [steps, setSteps] = useState([]);
  const [interactiveInfo, setInteractiveInfo] = useState(null); // {challengeURL, otp, acsTransID, flowType}
  const [mode, setMode] = useState('interactive'); // default mode
  const [runSearch, setRunSearch] = useState('');
  const iframeRef = useRef(null);

  useEffect(() => {
    fetchJSON('/scenarios').then(d => setScenarios(d.data || [])).catch(() => {});
  }, []);

  const loadRuns = useCallback(() => {
    setLoading(true);
    fetchJSON('/scenario-runs', { search: runSearch, page, per_page: PER_PAGE })
      .then(d => { setRuns(d.data || []); setTotal(d.total || 0); })
      .catch(() => {})
      .finally(() => setLoading(false));
  }, [page, runSearch]);

  useEffect(() => { loadRuns(); }, [loadRuns]);

  const runScenario = async (id) => {
    setRunning(id);
    setActiveRun(null);
    setSteps([]);
    setInteractiveInfo(null);
    try {
      // OReq is system-level — no cardholder data, always automatic
      const scenario = scenarios.find(s => s.id === id);
      const effectiveMode = scenario?.flowType === 'oreq' ? 'automatic' : mode;
      const result = await fetchJSON(`/scenarios/${id}/run`, { mode: effectiveMode }, 'POST');
      setActiveRun(result);
      const parsedSteps = typeof result.steps === 'string' ? JSON.parse(result.steps) : result.steps;
      setSteps(parsedSteps || []);

      // In interactive mode, extract the interactive_ready step info
      if (mode === 'interactive') {
        const readyStep = (parsedSteps || []).find(s => s.step === 'interactive_ready');
        if (readyStep && readyStep.response) {
          setInteractiveInfo({
            challengeURL: readyStep.response.challengeURL,
            otp: readyStep.response.otp,
            acsTransID: readyStep.response.acsTransID,
            flowType: readyStep.response.flowType,
          });
        }
      }
      loadRuns();
    } catch (e) {
      alert('Run failed: ' + e.message);
    } finally {
      setRunning(null);
    }
  };

  const completeInteractive = async () => {
    if (!activeRun) return;
    try {
      const result = await fetchJSON(`/scenario-runs/${activeRun.id}/complete`, {}, 'POST');
      setActiveRun(result);
      setInteractiveInfo(null);
      loadRuns();
    } catch (e) { /* ignore */ }
  };

  // OOB actions — call the ACS v1 endpoints directly (proxied by UI server)
  const oobAction = async (action) => {
    if (!interactiveInfo?.acsTransID) return;
    const id = interactiveInfo.acsTransID;
    try {
      const post = (url, body) => fetch(url, {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(body),
      }).then(r => { if (!r.ok) throw new Error(`HTTP ${r.status}`); return r.json(); });

      if (action === 'approve') {
        await post(`/v1/challenge/${id}/oob/result`, { approved: true });
        alert('OOB approved. Challenge should complete.');
      } else if (action === 'deny') {
        await post(`/v1/challenge/${id}/oob/result`, { approved: false });
        alert('OOB denied. Transaction marked as failed.');
      } else if (action === 'fallback') {
        await post(`/v1/challenge/${id}/oob/fallback`, {});
        // Fetch the new OTP generated by fallback
        try {
          const otpData = await fetchJSON(`/scenarios/otp/${id}`);
          setInteractiveInfo(prev => ({ ...prev, flowType: 'challenge_otp', otp: otpData.otp }));
        } catch (_) { /* OTP fetch failed, still switch to OTP view */
          setInteractiveInfo(prev => ({ ...prev, flowType: 'challenge_otp' }));
        }
        // Reload iframe without ?flow=oob to show OTP challenge page
        if (iframeRef.current) iframeRef.current.src = `/v1/challenge/${id}`;
      }
    } catch (e) {
      alert('Action failed: ' + e.message);
    }
  };

  const viewRun = async (id) => {
    try {
      const r = await fetchJSON(`/scenario-runs/${id}`);
      setActiveRun(r);
      const parsedSteps = typeof r.steps === 'string' ? JSON.parse(r.steps) : r.steps;
      setSteps(parsedSteps || []);
      setInteractiveInfo(null);

      // If it was an interactive run that's still active, restore info
      if (r.status === 'interactive') {
        const readyStep = (parsedSteps || []).find(s => s.step === 'interactive_ready');
        if (readyStep && readyStep.response) {
          setInteractiveInfo({
            challengeURL: readyStep.response.challengeURL,
            otp: readyStep.response.otp,
            acsTransID: readyStep.response.acsTransID,
            flowType: readyStep.response.flowType,
          });
        }
      }
    } catch (e) { /* ignore */ }
  };

  const totalPages = Math.ceil(total / PER_PAGE) || 1;

  return (
    <>
      <div className="page-header">
        <h1>Scenario Runner</h1>
        <p>Execute test scenarios — choose interactive or automatic mode</p>
      </div>

      {/* Mode selector + Quick-run bar */}
      <div className="table-card" style={{ marginBottom: 24 }}>
        <div className="table-toolbar">
          <div className="card-title">Run Scenarios</div>
          <div className="mode-toggle">
            <button className={`btn btn-small ${mode === 'interactive' ? 'btn-primary' : 'btn-secondary'}`}
              onClick={() => setMode('interactive')}>Interactive</button>
            <button className={`btn btn-small ${mode === 'automatic' ? 'btn-primary' : 'btn-secondary'}`}
              onClick={() => setMode('automatic')}>Automatic</button>
          </div>
        </div>
        <div style={{ padding: '8px 16px 4px', fontSize: 12, color: 'var(--text-muted)' }}>
          {mode === 'interactive'
            ? 'Interactive: initiates the transaction, shows the challenge page in a frame. You enter OTP, cancel, or manage OOB manually.'
            : 'Automatic: runs the full E2E scenario server-side, including OTP submission, cancel, or OOB actions.'}
        </div>
        <div style={{ padding: 16 }}>
          {scenarios.length === 0 ? (
            <div className="empty-state" style={{ padding: 16 }}>No scenarios configured. Go to Scenarios page to create one.</div>
          ) : (
            <div className="run-grid">
              {scenarios.map(s => (
                <div key={s.id} className="run-card">
                  <div style={{ flex: 1 }}>
                    <div style={{ fontWeight: 600, marginBottom: 4, color: 'var(--text-primary)' }}>{s.name}</div>
                    <div style={{ display: 'flex', gap: 6, flexWrap: 'wrap' }}>
                      <FlowBadge flow={s.flowType} />
                      <NetworkBadge network={s.network} />
                      <span className="badge badge-muted">{s.challengeAction}</span>
                    </div>
                    {s.description && <div style={{ fontSize: 12, color: 'var(--text-muted)', marginTop: 4 }}>{s.description}</div>}
                  </div>
                  {canDo('RunTestScenario') && (
                    <button className="btn btn-primary" disabled={running === s.id} onClick={() => runScenario(s.id)}>
                      {running === s.id ? 'Running…' : mode === 'interactive' ? 'Start' : 'Run'}
                    </button>
                  )}
                </div>
              ))}
            </div>
          )}
        </div>
      </div>

      {/* Interactive panel — challenge iframe + OTP + OOB controls */}
      {interactiveInfo && (
        <div className="interactive-panel" style={{ marginBottom: 24 }}>
          <div className="interactive-grid">
            {/* Left: Challenge iframe */}
            <div className="table-card">
              <div className="table-toolbar">
                <div className="card-title">Challenge Page</div>
                <button className="btn btn-small btn-secondary" onClick={() => {
                  if (iframeRef.current) {
                    const flowParam = interactiveInfo.flowType === 'challenge_unavailable' ? '?flow=fallback'
                      : (interactiveInfo.flowType === 'challenge_oob' || interactiveInfo.flowType === 'decoupled') ? '?flow=oob' : '';
                    iframeRef.current.src = `/v1/challenge/${interactiveInfo.acsTransID}${flowParam}`;
                  }
                }}>Reload</button>
              </div>
              <div style={{ padding: 0 }}>
                <iframe
                  ref={iframeRef}
                  src={`/v1/challenge/${interactiveInfo.acsTransID}${interactiveInfo.flowType === 'challenge_unavailable' ? '?flow=fallback' : (interactiveInfo.flowType === 'challenge_oob' || interactiveInfo.flowType === 'decoupled') ? '?flow=oob' : ''}`}
                  style={{ width: '100%', height: 520, border: 'none', borderRadius: '0 0 12px 12px', background: '#fff' }}
                  title="Challenge Page"
                />
              </div>
            </div>

            {/* Right: Controls */}
            <div>
              {/* OTP info card — only for OTP flows */}
              {interactiveInfo.flowType !== 'challenge_oob' && interactiveInfo.flowType !== 'decoupled' && (
                <div className="table-card" style={{ marginBottom: 16 }}>
                  <div className="table-toolbar">
                    <div className="card-title">OTP Code</div>
                  </div>
                  <div style={{ padding: 20, textAlign: 'center' }}>
                    <div className="otp-display">{interactiveInfo.otp || '—'}</div>
                    <div style={{ fontSize: 12, color: 'var(--text-muted)', marginTop: 8 }}>
                      Enter this code in the challenge page
                    </div>
                    <button className="btn btn-small btn-secondary" style={{ marginTop: 8 }}
                      onClick={() => { navigator.clipboard.writeText(interactiveInfo.otp || ''); }}>
                      Copy to Clipboard
                    </button>
                  </div>
                </div>
              )}

              {/* PIN info card — fetches PIN for second factor */}
              {interactiveInfo.pin && (
                <div className="table-card" style={{ marginBottom: 16 }}>
                  <div className="table-toolbar">
                    <div className="card-title">Card PIN (2nd Factor)</div>
                  </div>
                  <div style={{ padding: 20, textAlign: 'center' }}>
                    <div className="otp-display">{interactiveInfo.pin}</div>
                    <div style={{ fontSize: 12, color: 'var(--text-muted)', marginTop: 8 }}>
                      Enter this PIN on the second factor page
                    </div>
                    <button className="btn btn-small btn-secondary" style={{ marginTop: 8 }}
                      onClick={() => { navigator.clipboard.writeText(interactiveInfo.pin || ''); }}>
                      Copy to Clipboard
                    </button>
                  </div>
                </div>
              )}
              {!interactiveInfo.pin && interactiveInfo.flowType !== 'challenge_unavailable' && (
                <button className="btn btn-small btn-secondary" style={{ marginBottom: 12 }}
                  onClick={async () => {
                    try {
                      const data = await fetchJSON(`/scenarios/pin/${interactiveInfo.acsTransID}`);
                      if (data.pin) setInteractiveInfo(prev => ({ ...prev, pin: data.pin }));
                    } catch (_) { /* PIN not yet generated */ }
                  }}>
                  Fetch PIN (if 2nd factor active)
                </button>
              )}

              {/* OOB controls — only for OOB/decoupled flows */}
              {(interactiveInfo.flowType === 'challenge_oob' || interactiveInfo.flowType === 'decoupled') && (
                <div className="table-card" style={{ marginBottom: 16 }}>
                  <div className="table-toolbar">
                    <div className="card-title">OOB Actions</div>
                  </div>
                  <div style={{ padding: 16, display: 'flex', flexDirection: 'column', gap: 8 }}>
                    <div style={{ fontSize: 12, color: 'var(--text-muted)', marginBottom: 4 }}>
                      Simulate the out-of-band authenticator response:
                    </div>
                    <button className="btn btn-primary" onClick={() => oobAction('approve')}>
                      Approve (OOB)
                    </button>
                    <button className="btn btn-danger" onClick={() => oobAction('deny')}>
                      Deny (OOB)
                    </button>
                    <button className="btn btn-secondary" onClick={() => oobAction('fallback')}>
                      Fallback to OTP
                    </button>
                  </div>
                </div>
              )}

              {/* Transaction info */}
              <div className="table-card" style={{ marginBottom: 16 }}>
                <div className="table-toolbar">
                  <div className="card-title">Transaction</div>
                </div>
                <div style={{ padding: 16, fontSize: 12 }}>
                  <div style={{ marginBottom: 6 }}>
                    <span style={{ color: 'var(--text-muted)' }}>ACS Trans ID:</span>
                    <div className="mono" style={{ marginTop: 2, wordBreak: 'break-all' }}>{interactiveInfo.acsTransID}</div>
                  </div>
                  <div>
                    <span style={{ color: 'var(--text-muted)' }}>Flow:</span>
                    <div style={{ marginTop: 2 }}><FlowBadge flow={interactiveInfo.flowType} /></div>
                  </div>
                </div>
              </div>

              {/* Complete button */}
              <button className="btn btn-primary" style={{ width: '100%' }} onClick={completeInteractive}>
                Mark as Complete
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Automatic run detail (non-interactive) */}
      {activeRun && !interactiveInfo && steps.length > 0 && (
        <div style={{ marginBottom: 24 }}>
          <div className="table-card">
            <div className="table-toolbar">
              <div className="card-title">
                Run #{activeRun.id} — {activeRun.scenarioName}
                <RunStatusBadge status={activeRun.status} />
              </div>
              <div style={{ fontSize: 12, color: 'var(--text-muted)' }}>{activeRun.durationMs}ms</div>
            </div>
            <div style={{ padding: 16 }}>
              <div className="steps-list">
                {steps.map((step, i) => (
                  <div key={i} className={`step-item step-${step.status}`}>
                    <div className="step-header">
                      <span className={`step-dot ${step.status === 'ok' ? 'step-dot-ok' : 'step-dot-fail'}`} />
                      <span className="step-name">{step.step}</span>
                      <span className="step-time">{step.durationMs}ms</span>
                    </div>
                    {step.error && <div className="step-error">{step.error}</div>}
                    {step.response && (
                      <details className="step-detail" open={step.step === 'fetch_otp'}>
                        <summary>Response</summary>
                        <pre className="step-json">{JSON.stringify(step.response, null, 2)}</pre>
                      </details>
                    )}
                  </div>
                ))}
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Run history */}
      <div className="table-card">
        <div className="table-toolbar">
          <div className="card-title">Run History ({total})</div>
          <SearchInput value={runSearch} onChange={v => { setRunSearch(v); setPage(1); }} placeholder="Search runs…" />
        </div>
        <div className="table-wrap">
          {loading ? (
            <div className="spinner-wrap"><div className="spinner" /></div>
          ) : (
            <table>
              <thead>
                <tr>
                  <th>ID</th><th>Scenario</th><th>Flow</th><th>Status</th>
                  <th>Mode</th><th>Duration</th><th>ACS Trans ID</th><th>Started</th><th>Actions</th>
                </tr>
              </thead>
              <tbody>
                {runs.map(r => (
                  <tr key={r.id}>
                    <td className="mono">{r.id}</td>
                    <td style={{ fontWeight: 500, color: 'var(--text-primary)' }}>{r.scenarioName}</td>
                    <td><FlowBadge flow={r.flowType} /></td>
                    <td><RunStatusBadge status={r.status} /></td>
                    <td><span className="badge badge-muted">{r.status === 'interactive' ? 'Interactive' : 'Auto'}</span></td>
                    <td className="mono">{r.durationMs}ms</td>
                    <td className="mono truncate" title={r.acsTransactionId}>
                      {r.acsTransactionId ? r.acsTransactionId.slice(0, 8) + '…' : '—'}
                    </td>
                    <td>{formatDate(r.startedAt)}</td>
                    <td>
                      <button className="btn btn-small btn-secondary" onClick={() => viewRun(r.id)}>View</button>
                    </td>
                  </tr>
                ))}
                {runs.length === 0 && (
                  <tr><td colSpan={9} className="empty-state">No runs yet. Select a scenario above to run it.</td></tr>
                )}
              </tbody>
            </table>
          )}
        </div>
        <Pagination page={page} totalPages={totalPages} total={total} perPage={PER_PAGE} onPageChange={setPage} />
      </div>
    </>
  );
}

function RunStatusBadge({ status }) {
  const map = {
    pending: ['badge-muted', 'Pending'],
    running: ['badge-yellow', 'Running'],
    interactive: ['badge-cyan', 'Interactive'],
    completed: ['badge-green', 'Completed'],
    failed: ['badge-red', 'Failed'],
  };
  const [cls, label] = map[status] || ['badge-muted', status];
  return <span className={`badge ${cls}`} style={{ marginLeft: 8 }}>{label}</span>;
}

function formatDate(iso) {
  if (!iso) return '—';
  const d = new Date(iso);
  return d.toLocaleString('en-GB', {
    day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit', second: '2-digit', hour12: false,
  });
}