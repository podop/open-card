package dto

// AReqDTO is the JSON body received from the 3DS Server (AReq message).
// Field names follow the EMV 3DS spec exactly.
type AReqDTO struct {
	// Required fields
	MessageType         string `json:"messageType" binding:"required,eq=AReq"`
	MessageVersion      string `json:"messageVersion" binding:"required"`
	MessageCategory     string `json:"messageCategory" binding:"required"`
	DeviceChannel       string `json:"deviceChannel" binding:"required"`
	ThreeDSServerTransID string `json:"threeDSServerTransID" binding:"required,uuid"`
	DSTransID           string `json:"dsTransID" binding:"required,uuid"`

	// Card
	AcctNumber string `json:"acctNumber" binding:"required"`

	// Merchant
	MerchantName    string `json:"merchantName" binding:"required"`
	MerchantCountry string `json:"merchantCountry" binding:"required"`
	MerchantID      string `json:"merchantID"`

	// Purchase (required for PA)
	PurchaseAmount   *string `json:"purchaseAmount"`
	PurchaseCurrency *string `json:"purchaseCurrency"`
	PurchaseExponent *int    `json:"purchaseExponent"`

	// Browser info (browser-based channel, DeviceChannel=02)
	BrowserAcceptHeader      *string `json:"browserAcceptHeader"`       // required; AN max 2048
	BrowserIP                *string `json:"browserIP"`                 // optional; AN max 45
	BrowserUserAgent         *string `json:"browserUserAgent"`          // required; AN max 2048
	BrowserLanguage          *string `json:"browserLanguage"`           // required; AN max 8
	BrowserColorDepth        *string `json:"browserColorDepth"`         // required; "1"|"4"|"8"|"15"|"16"|"24"|"32"|"48"
	BrowserScreenHeight      *string `json:"browserScreenHeight"`       // required; N max 6
	BrowserScreenWidth       *string `json:"browserScreenWidth"`        // required; N max 6
	BrowserTZ                *int    `json:"browserTZ"`                 // required; integer -840 to 720
	BrowserJavaEnabled       *bool   `json:"browserJavaEnabled"`        // required
	BrowserJavascriptEnabled *bool   `json:"browserJavascriptEnabled"`  // optional

	// SDK fields (app-based channel, DeviceChannel=01)
	// SDKTransID is the UUID generated by the SDK for this transaction.
	SDKTransID *string `json:"sdkTransID"`
	// SDKEncData is a JWE compact serialisation of the device info, encrypted
	// with the ACS public key (RSA-OAEP / A128CBC-HS256 per EMV 3DS spec).
	SDKEncData *string `json:"sdkEncData"`
	// SDKEphemPubKey is the SDK's ephemeral EC public key (JWK JSON object) used
	// to establish the secure channel for CReq/CRes messages.
	SDKEphemPubKey *string `json:"sdkEphemPubKey"`
	// SDKAppID is the UUID identifying the SDK installation on the device.
	SDKAppID *string `json:"sdkAppID"`
	// SDKReferenceNumber identifies the SDK vendor and version.
	SDKReferenceNumber *string `json:"sdkReferenceNumber"`
	// SDKMaxTimeout is the maximum time (minutes) for OOB authentication.
	// required; N-2; range 05–99.
	SDKMaxTimeout *int `json:"sdkMaxTimeout"`

	// threeDSRequestorChallengeInd: "01"=no preference, "02"=no challenge requested,
	// "03"=challenge requested (3DS Requestor preference), "04"=challenge requested (mandate).
	ThreeDSRequestorChallengeInd *string `json:"threeDSRequestorChallengeInd"`
	// threeDSRequestorDecReqInd: "Y" = decoupled authentication is requested, "N" = not requested.
	ThreeDSRequestorDecReqInd *string `json:"threeDSRequestorDecReqInd"`

	// 3RI fields (3DS Requestor Initiated, DeviceChannel=03)
	// ThreeRIInd identifies the type of 3RI request.
	// required for DeviceChannel=03; N-2; see spec Table A.9.
	ThreeRIInd *string `json:"threeRIInd"`

	// 3DS Method notification URL
	ThreeDSMethodNotifURL string `json:"threeDSMethodNotificationURL"`
}

// AResDTO is the JSON body returned to the 3DS Server (ARes message).
type AResDTO struct {
	MessageType      string  `json:"messageType"`
	MessageVersion   string  `json:"messageVersion"`
	ACSTransID       string  `json:"acsTransID"`
	DSTransID        string  `json:"dsTransID"`
	ServerTransID    string  `json:"threeDSServerTransID"`
	TransStatus      string  `json:"transStatus"`
	// transStatusReason is required when transStatus is N, U, or R (Table A.9).
	TransStatusReason *string `json:"transStatusReason,omitempty"`
	AuthValue        *string `json:"authenticationValue,omitempty"`
	ECI              *string `json:"eci,omitempty"`
	// Challenge redirect URL (spec field name: acsURL, Table B.2).
	ACSURL           *string `json:"acsURL,omitempty"`
	ACSReferenceNumber string `json:"acsReferenceNumber"`
}

// CReqDTO is the JSON body for a Challenge Request from the 3DS Server.
type CReqDTO struct {
	MessageType          string  `json:"messageType" binding:"required,eq=CReq"`
	MessageVersion       string  `json:"messageVersion" binding:"required"`
	ThreeDSServerTransID string  `json:"threeDSServerTransID" binding:"required,uuid"`
	ACSTransID           string  `json:"acsTransID" binding:"required,uuid"`
	// ChallengeWindowSize: optional; "01"=250×400 "02"=390×400 "03"=500×600 "04"=600×400 "05"=full-screen
	ChallengeWindowSize  string  `json:"challengeWindowSize"`
	// SDK fields — required when the originating AReq was app-based (DeviceChannel=01)
	SDKTransID      *string `json:"sdkTransID"`      // UUID
	SDKCounterStoA  *string `json:"sdkCounterStoA"`  // N-6; counter from SDK to ACS
}

// CResDTO is the JSON body for a Challenge Response returned to the browser/SDK.
type CResDTO struct {
	MessageType    string `json:"messageType"`
	MessageVersion string `json:"messageVersion"`
	ACSTransID     string `json:"acsTransID"`
	// ThreeDSServerTransID is mandatory in CRes (Table B.5).
	ThreeDSServerTransID string `json:"threeDSServerTransID,omitempty"`
	TransStatus    string `json:"transStatus"`
	// ChallengeCompletionInd: Y = challenge complete, N = more exchanges needed (Table B.5).
	ChallengeCompletionInd string `json:"challengeCompletionInd,omitempty"`
}

// ThreeDSMethodFormDTO is the posted form data for the 3DS Method endpoint.
type ThreeDSMethodFormDTO struct {
	ThreeDSMethodData string `form:"threeDSMethodData" binding:"required"`
}

// OTPSubmitDTO is the challenge OTP submission form body.
type OTPSubmitDTO struct {
	ACSTransID string `json:"acsTransID" binding:"required,uuid"`
	OTPCode    string `json:"otpCode" binding:"required,len=6"`
}

// RResDTO is the Result Response sent by the DS to the ACS in reply to an RReq.
type RResDTO struct {
	MessageType          string `json:"messageType" binding:"required,eq=RRes"`
	MessageVersion       string `json:"messageVersion" binding:"required"`
	ThreeDSServerTransID string `json:"threeDSServerTransID" binding:"required,uuid"`
	ACSTransID           string `json:"acsTransID" binding:"required,uuid"`
	DSTransID            string `json:"dsTransID" binding:"required,uuid"`
	// ResultsStatus: "01" = results acknowledged (only valid value per spec).
	ResultsStatus string `json:"resultsStatus" binding:"required"`
}

// OReqDTO is the Operating Request sent by ACS to DS per EMV 3DS spec.
type OReqDTO struct {
	MessageType        string          `json:"messageType"`
	MessageVersion     string          `json:"messageVersion"`
	ACSOperatorID      string          `json:"acsOperatorID"`
	ACSReferenceNumber string          `json:"acsReferenceNumber"`
	ACSAvailability    string          `json:"acsAvailability"`
	ACSStartProtoVer   string          `json:"acsStartProtocolVersion,omitempty"`
	ACSEndProtoVer     string          `json:"acsEndProtocolVersion,omitempty"`
	CardRangeData      []OReqCardRange `json:"cardRangeData,omitempty"`
}

// OReqCardRange represents a single card range entry within OReq.
type OReqCardRange struct {
	StartRange       string `json:"startRange"`
	EndRange         string `json:"endRange"`
	ActionInd        string `json:"actionInd,omitempty"`
	ACSStartProtoVer string `json:"acsStartProtocolVersion,omitempty"`
	ACSEndProtoVer   string `json:"acsEndProtocolVersion,omitempty"`
}

// OResDTO is the Operating Response from the DS acknowledging the OReq.
type OResDTO struct {
	MessageType        string `json:"messageType"`
	MessageVersion     string `json:"messageVersion"`
	ACSOperatorID      string `json:"acsOperatorID"`
	ACSReferenceNumber string `json:"acsReferenceNumber"`
}

// ErrorDTO is the standard ACS error response.
type ErrorDTO struct {
	MessageType        string `json:"messageType"`
	MessageVersion     string `json:"messageVersion"`
	ErrorCode          string `json:"errorCode"`
	ErrorComponent     string `json:"errorComponent"`
	ErrorDescription   string `json:"errorDescription"`
	ErrorDetail        string `json:"errorDetail"`
	ErrorMessageType   string `json:"errorMessageType"`
}
